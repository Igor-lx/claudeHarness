import { defineConfig } from "vitest/config";
import react from "@vitejs/plugin-react";

// Один конфиг на сборку и на тесты: раннер читает секцию `test` отсюда же.
// Двумя файлами они разъезжались бы в настройках, общих для обоих, — в первую
// очередь в разрешении путей.
export default defineConfig({
  plugins: [react()],
  test: {
    // Тесты компонентов читают разметку, а разметки в окружении node нет.
    // Без этой строки первый же тест на компонент падает на `document`.
    environment: "jsdom",
    globals: false,
    // Область сбора названа явно: набор тестов на словарь области инструмента
    // лежит в папке обвязки, и умолчание раннера туда заходит, а вот умолчания
    // других раннеров — нет. Явный список не зависит от того, чей раннер.
    include: ["src/**/*.test.{ts,tsx}", ".claude/tools/**/*.test.mjs"],
  },
});
