import { defineConfig } from "vitest/config";
import react from "@vitejs/plugin-react";

// Один конфиг на сборку и на тесты: раннер читает секцию `test` отсюда же.
// Двумя файлами они разъезжались бы в настройках, общих для обоих, — в первую
// очередь в разрешении путей.
export default defineConfig({
  plugins: [react()],
  test: {
    // Корень ПРОГОНА назван явно, и это не украшение: проект, чей сборщик
    // собирает поддерево — `root: "client"`, — сдвигает вместе с ним и поиск
    // тестов. Образцы ниже написаны от корня репозитория, и без этой строки
    // раннер не находит ни одного файла, отвечая «No test files found».
    // Замерено посадкой стенда с двумя деревьями.
    root: ".",
    // Тесты компонентов читают разметку, а разметки в окружении node нет.
    // Без этой строки первый же тест на компонент падает на `document`.
    environment: "jsdom",
    globals: false,
    // Модули стилей обрабатываются и в тестах. Под умолчанием раннера они
    // подменяются заглушкой, у которой ОБРАЩЕНИЕ работает, а ПЕРЕЧИСЛЕНИЕ
    // нет: `styles.heading` отдаёт имя, а `Object.keys(styles)` — пусто.
    // Слияние карты классов идёт по ключам, и под заглушкой оно молча теряет
    // собственные классы компонента: тест видит поведение, которого в сборке
    // не будет. Обрабатываются только модули — обычные листы тестам не нужны,
    // и платить за них временем прогона не за что.
    css: { include: [/.module./] },
    // Уборка после каждого теста. При `globals: false` библиотека тестов
    // не регистрирует её сама, и вторая же отрисовка находит две копии
    // компонента — с сообщением, которое читается как дефект компонента.
    setupFiles: ["./src/tests/setup.ts"],
    // Область сбора названа явно: набор тестов на словарь области инструмента
    // лежит в папке обвязки, и умолчание раннера туда заходит, а вот умолчания
    // других раннеров — нет. Явный список не зависит от того, чей раннер.
    include: ["src/**/*.test.{ts,tsx}", ".claude/tools/**/*.test.mjs"],
  },
});
