/** Модель одной строкой — `П1:вид:пометка:сдвиг;…` — разобранная. */
const modelRowsOf = (text) =>
  (text ?? "")
    .split(";")
    .filter(Boolean)
    .map((one) => {
      const [mid, sort, raw, delta] = one.split(":");
      const [mark, word] = owedSplit(raw ?? "");
      return {
        mid,
        n: Number((mid ?? "").slice(1)),
        sort,
        mark,
        owed: BAR_OWED.includes(word) ? word : "",
        held: word === BAR_HELD,
        delta: delta ?? "",
        level: MODEL_LEVEL[sort] ?? "",
      };
    });

