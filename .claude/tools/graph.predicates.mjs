/**
 * Прогон таблицы. Возвращает список расхождений — пустой, когда всё сходится.
 *
 * Инструмент зовёт это на КАЖДОМ запуске и отказывается работать при непустом
 * списке. Причина в том, что «запустить тесты после правки» иначе держится
 * памятью: набор гоняется, когда о нём вспомнили, а инструмент вызывают
 * постоянно — и сломанный словарь виден в тот же миг, а не в конце дня.
 *
 * Предикат берётся из собственного пространства имён модуля, а не из таблицы
 * соответствия рядом. Таблица тут стояла и была **третьим** рукописным списком
 * тех же имён — после списка в наборе тестов и списка покрытия; оба уже убраны
 * тем же движением. Стоила она не аккуратности: предикат со случаями, но не
 * внесённый в неё, ронял инструмент стек-трейсом `BY_NAME[name] is not a
 * function` — то есть словарь, чей контракт «отказаться внятно, а не ответить
 * неверно», отказывался невнятно. Проверено подсадкой.
 *
 * Имя из таблицы, которого в словаре нет вовсе (опечатка в случае), теперь
 * тоже расхождение, а не падение.
 */
export const selfCheck = () => {
  const failed = [];
  // Предикат БЕЗ ЕДИНОГО случая — не расхождение, а дыра: перебор ниже его
  // просто не встретит, и словарь промолчит о том, что половину его никто
  // не проверяет. Спрашивается это здесь, а не только набором тестов:
  // набор приезжает в проект, но зовёт его раннер ПРОЕКТА, и в
  // монорепозитории, где корневой скрипт тестов делегирует пакетам, тесты
  // обвязки не запускаются вовсе. Гарантия обвязки не может зависеть от
  // того, как устроен чужой раннер; инструмент зовут постоянно, и здесь
  // она держится сама.
  const covered = new Set(PREDICATE_CASES.map(([name]) => name));
  for (const [name, value] of Object.entries(vocabulary))
    if (typeof value === "function" && value.length === 1 && !covered.has(name))
      failed.push(name + " — предикат области без единого случая");
  for (const [name, input, want] of PREDICATE_CASES) {
    const predicate = vocabulary[name];
    if (typeof predicate !== "function") {
      failed.push(`${name} — такого предиката в словаре нет`);
      continue;
    }
    const got = predicate(input);
    if (got !== want) failed.push(`${name}(${input}) = ${got}, ждали ${want}`);
  }
  return failed;
};

/** Язык модуля: TypeScript И обычный JavaScript.
 *
 * Умолчание обвязки — TypeScript, и половина планки стоит на его строгости. Но
 * умолчание говорит, на чём НАЧИНАЮТ проект, а не что инструмент способен
 * прочесть: живой проект на обычном JavaScript существует, и обвязку в него
 * сажают так же. Пока опознавался один язык, такой проект был для инструмента
 * ПУСТ — «файлов кода: ноль» при шести файлах на диске, — и молчали разом карта,
 * реестр тестов, замер чтения и поиск предмета для разделов планки.
 *
 * Расхождение с умолчанием этим не отменяется: оно называется отчётом посадки и
 * платится тем, что критерии о строгости проверять нечем. Но невидимость и
 * несогласие — разные вещи, и вторая лучше первой.
 */

/** Расширение кода или листа стилей — одним образцом на весь инструмент.
 *
 * Заведён после того, как восемь мест спрашивали его порознь и каждое называло
 * один язык стилей из пяти. Проект на обычных модулях CSS от этого терял адреса
 * в прозе, разбор коротких имён и опознание токенов — по одной сверке за место,
 * и каждый раз молча. Один образец нельзя поправить наполовину.
 */
export const CODE_OR_STYLE = /\.(tsx?|css|scss|sass|less|styl)$/;

/** Языки стилей — ОДНОЙ строкой, из которой собираются все образцы.
 *
 * Предикаты уже сводили это к одному месту, но образцы, перечисляющие
 * расширения внутри себя, остались порознь: их восемь, и каждый называл
 * один язык стилей. Самый дорогой — тот, которым инструмент ЧИТАЕТ адреса
 * из базы: файл `.css`, названный в карте, не разбирался как адрес вовсе,
 * то есть запись была, и не видел её никто. Проект на обычных модулях CSS
 * не мог закрыть покрытие карты в принципе.
 */
export const STYLE_ALT = "css|scss|sass|less|styl";

/** Код или стиль — альтернатива для образцов, а не готовый образец. */
export const CODE_STYLE_ALT = "[jt]sx?|" + STYLE_ALT;

/** Разбор вывода сверки: секция → МНОЖЕСТВО её строк находок.
 *
 * Аргументов два намеренно. Перенос строк — соглашение вызывающего, а не
 * этого разбора; заодно два аргумента выводят функцию из-под переборa
 * самопроверки, который умеет только да/нет, а здесь ответ — отображение.
 * Держит её набор тестов, а не таблица случаев.
 *
 * Прежде на этом месте стоял ФЛАГ «красная или нет», и его не хватало
 * сразу дважды. Сверка, красная ДО поломки, оставалась красной и после —
 * флаг не менялся, и рецепт числился промолчавшим. То есть в живом
 * проекте, где красные сверки есть по определению, фальсифицировать их
 * было нельзя вовсе: здоровая сверка выглядела сломанной.
 */
export const sectionsOf = (out, newline) => {
  const found = new Map();
  const lines = out.split(newline);
  for (let i = 0; i < lines.length; i += 1) {
    const head = /^=== (.+) ===$/.exec(lines[i]);
    if (head === null) continue;
    const red = new Set();
    for (let j = i + 1; j < lines.length && !/^=== /.test(lines[j]); j += 1)
      if (/^ {4}\S/.test(lines[j])) red.add(lines[j]);
    found.set(head[1], red);
  }
  return found;
};

/** Что сделал посаженный слом — по ВСЕМУ прогону, а не в одной секции.
 *
 * Четыре исхода:
 *
 *   секции нет в выводе после поломки          → рецепт устарел;
 *   секция появилась, которой не было          → поймала;
 *   в целевой секции прибавились строки        → поймала;
 *   целевая не изменилась, прибавилось в другой→ поломка ушла не туда:
 *     рецепт мимо, и сверка, ради которой он написан, ни при чём;
 *   не изменилось нигде                        → не дошла ни до одной.
 *
 * Последнее читается «здесь ломать нечего ЛИБО сверка слепа» — две вещи, и
 * разделить их нечем. Но прежде в этой куче лежали ещё две: отравленная
 * соседом песочница и сверка, красная до поломки. Обе закрыты, и остаток
 * назван честно, а не выдан за одну болезнь.
 *
 * Часть сверок печатает секцию ТОЛЬКО когда есть что сказать: звенья
 * цепочки без инструмента, версия среды, скрипты без описания. У здоровой
 * такой сверки секции в выводе нет вовсе, и «нет секции» для неё —
 * ЗДОРОВЬЕ, а не устаревший рецепт: появление секции после поломки и есть
 * её срабатывание. Прежде прогон объявлял неисправимым то, что исправно.
 */
export const classifyRun = (clean, after, section) => {
  const grew = (was, now) => [...now].some((l) => !was.has(l));
  const wasThere = clean.has(section);
  if (!after.has(section))
    return {
      how: "broken",
      why: wasThere
        ? " — секция пропала из вывода"
        : " — секции в выводе нет ни до, ни после",
    };
  if (!wasThere) return { how: "caught" };
  if (grew(clean.get(section), after.get(section))) return { how: "caught" };
  for (const [name, red] of after) {
    if (name === section) continue;
    if (!clean.has(name) || grew(clean.get(name), red))
      return {
        how: "astray",
        why: " — легла, но её приняла сверка «" + name + "»",
      };
  }
  return { how: "nowhere" };
};
