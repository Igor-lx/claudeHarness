/** Тест: лежит в папке слоя `tests/` либо назван суффиксом. */
// Имена тестов бывают двух видов, и второй не реже первого. `.spec` — форма из
// мира, откуда пришли раннеры: её везут все поколения инструментов, и живой
// проект зовёт свои тесты так же часто, как `.test`.
//
// Пока опознавался один вид, инструмент отвечал «тестовых файлов: ноль» на
// проекте, где раннер собирал тридцать шесть зелёных тестов, — а сверка
// покрытия тестов была при этом ЗЕЛЕНОЙ, потому что не видела ничего. Найдено
// посадкой в чужую библиотеку.
export const isTestPath = (f) =>
  /\/tests\//.test(f) ||
  /\/__tests__\//.test(f) ||
  /\.(test|spec)\.[jt]sx?$/.test(f);

/** Лист стилей. В граф импортов не входит — его подключает сборщик.
 *
 * Собираются ВСЕ языки стилей, а не один. Пока опознавался только `.scss`,
 * проект на обычных модулях CSS проходил как проект без стилей вовсе: сто
 * девяносто непустых строк — больше, чем весь его код — не попадали ни в карту,
 * ни в замер чтения, ни в поиск предмета для раздела планки о стилях. Раздел
 * из-за этого выключался молча, и сверка применимости была зелёной. */
export const isStylePath = (f) => /\.(css|scss|sass|less|styl)$/.test(f);

/** Документ. */
export const isDocPath = (f) => /\.md$/.test(f);

/**
 * Исполняемый модуль: то, у чего есть форма и ответ, то есть контракт. Тест
 * сюда не входит — он сам проверка, поверхности у него нет.
 */
export const isCodePath = (f) => /\.[jt]sx?$/.test(f) && !isTestPath(f);

/**
 * То, чья правка меняет наблюдаемое поведение продукта: код или стиль. Стиль
 * входит намеренно — в графе импортов его не видно, а краску он меняет.
 * Документ и тест — нет: первый ничего не исполняет, второй и есть проверка.
 */
export const touchesRuntime = (f) => isCodePath(f) || isStylePath(f);

/**
 * Позиция в строке приходится на комментарий. Нужен там, где сверка спрашивает
 * «существует ли имя в ИСПОЛНЯЕМОМ тексте»: иначе она держится за собственное
 * эхо — переименовали по всему коду, оставили старое имя в комментарии, и
 * запись считается живой.
 */
export const inComment = (line, at) => {
  const before = line.slice(0, at);
  return before.includes("//") || /^\s*(\*|\/\*)/.test(line);
};

/**
 * Текст модуля БЕЗ блочных комментариев: граф строится по коду, а не по
 * рассказу о нём.
 *
 * Разбор импортов шёл по сырому тексту, и закомментированный пример в хвосте
 * файла давал НАСТОЯЩЕЕ ребро графа: файл импортировал сам себя и стоял в
 * собственном радиусе поражения. Хуже другое — закомментированный импорт
 * числился живым потребителем, и мёртвый экспорт выглядел используемым.
 *
 * Снимается только комментарий, ОТКРЫТЫЙ С НАЧАЛА СТРОКИ, и это не
 * упрощение. Сочетание косой со звёздочкой сплошь и рядом стоит внутри строк
 * — любой образец пути вида двух звёздочек со слэшем несёт его, — и жадное
 * снятие съело бы код до следующего закрытия. Закомментированный же блок
 * начинается с начала строки всегда.
 *
 * Строчный комментарий тут ни при чём: образец импорта требует начала
 * строки, а две косые его не пускают.
 *
 * Переводы строк сохраняются: номера строк не должны поехать.
 */
export const codeOf = (text) =>
  text.replace(/^[ \t]*\/\*[\s\S]*?\*\//gm, (m) => m.replace(/[^\n]/g, ""));
