/** Беспредметен ли критерий планки НА ЭТОЙ ПРАВКЕ — чистая её часть.
 *
 * На входе строка `<критерий>|<признак>=<0|1>,…` — сам критерий и то, что
 * инструмент замерил в предмете правки. На выходе причина словами либо
 * пустая строка: предмет есть, и отвечает сессия.
 *
 * **Зачем.** Раздел политики объявляется живым или мёртвым на ВЕСЬ проект, и
 * мёртвый в протокол не попадает вовсе. Живой попадает целиком — даже когда
 * эта правка его предмета не касается: раздел стилей живой, потому что листы
 * у проекта есть, а правка тронула один файл кода. Сессия писала «предмета
 * нет» руками по одиннадцати строкам, и это почти сорок процентов всей
 * работы свода — замерено на проходе по стенду: из ста сорока девяти строк
 * пятьдесят девять были «нет предмета».
 *
 * **Отбор узкий намеренно.** Сюда попадает только то, что доказуемо из
 * предмета: файла такого рода в правке нет, эффекта нет, списка нет,
 * манифест не тронут. Суждения — «предметной логики тут нет», «горячего
 * пути нет» — не попадают и попасть не могут: машина их не выводит, а
 * поставленное ею «нет предмета» там, где предмет есть, — это ровно то
 * зелёное без проверки, от которого свод и заведён.
 *
 * **Поставленное не заперто.** Инструмент заполняет клетку, сессия вправе
 * переписать: строка из протокола не исчезает, исчезает только её набивка.
 */
