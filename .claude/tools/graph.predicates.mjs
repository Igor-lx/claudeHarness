/** Номера строк модели, названные текстом: по одному и диапазоном
 * «П3–П7». Номер называется целиком: П2 не отвечает за П20.
 *
 * Диапазон — опора, а не ответ. Строку, о которой модель СПРАШИВАЕТ, —
 * сдвиг, вопрос к основанию, — называют её номером: `alone` отдаёт только
 * такие. Прежде «П1–П17 разобраны» отвечало на каждый вопрос модели разом,
 * не ответив ни на один: замерено кривой кнопкой на мини-стенде, где так
 * прошли новое состояние, обход входа чужой папки и второй источник. */
const citedIds = (text, alone = false) => {
  const out = new Set();
  for (const m of (text ?? "").matchAll(
    /(^|[^А-Яа-яA-Za-z0-9])П([0-9]+)(?:\s*[–—-]\s*П?([0-9]+))?(?![0-9])/g,
  )) {
    if (alone && m[3] !== undefined) continue;
    const from = Number(m[2]);
    const to = m[3] === undefined ? from : Number(m[3]);
    for (let k = from; k <= Math.max(from, to); k += 1) out.add(k);
  }
  return out;
};

/** Чем записан известный дефект, если факт модели им является: пункт долга
 * перехода либо открытая строка реестра находок. Пишется в пометке строки
 * модели после точки: «против правила · долг перехода». */
export const BAR_OWED = ["долг перехода", "находка реестра"];
/** Факт, названный записью решения: разработчик сказал «оставляем» либо «не
 * сейчас», и факт законен. Пишется в пометке так же, после точки. */
export const BAR_HELD = "решение";
const owedSplit = (raw) => {
  for (const word of [...BAR_OWED, BAR_HELD]) {
    if (raw === word) return ["", word];
    if (raw.endsWith(" · " + word)) return [raw.slice(0, -(word.length + 3)), word];
  }
  return [raw, ""];
};
/** Пометка строки модели — чем записан известный дефект, либо пусто. */
export const barOwedOf = (mark) => {
  const word = owedSplit(mark ?? "")[1];
  return BAR_OWED.includes(word) ? word : "";
};

