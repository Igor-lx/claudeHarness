/** Называет ли текст адрес ЦЕЛИКОМ, а не как начало другого адреса.
 *
 * Вход — `адрес|текст`. Папка засчитывается с косой на конце и без неё.
 * Прежде запись решения узнавалась вхождением подстроки, и адрес `src/`
 * находился в любом тексте, где назван хоть один путь под ним: тест,
 * объявленный вне своей папки, проходил без всякого решения о нём.
 */
export const namesAddress = (row) => {
  const cut = row.indexOf("|");
  const addr = row.slice(0, cut).replace(/\/$/, "");
  const esc = addr.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(
    "(^|[\\s`(«\"'])" + esc + "/?(?=$|[\\s`)»\"',.;:])",
    "m",
  ).test(row.slice(cut + 1));
};

/** Входит ли критерий в архитектурное ядро. Наружу — для свода: он печатает
 * такие строки помеченными, чтобы клетка основания не выглядела лишней. */
export const barCoreCriterion = (id) => BAR_CORE.has(id);
export const barRowFault = (row) => {
  // Шестая клетка — идентификатор критерия. Прежде строка несла пять: ядро
  // планки спрашивают поимённо, и без имени спросить его нечем.
  const [kind, outcome, addr, what, fate, id] = row
    .split("|")
    .map((c) => c.trim());
  if (outcome === "") return "исход не поставлен";
  // «Лозунг» — не исход, а признак того, что исхода тут быть не может.
  //
  // Политика объявляет часть пунктов лозунгами прямо: «у него нет величины
  // отсчёта и способа измерения, поэтому по нему нельзя ни оценить дифф, ни
  // сослаться на него как на нарушение». Протокол при этом требовал исход по
  // каждому и числил такие строки дырами — то есть машина требовала ровно
  // той оценки, которую доктрина объявила невозможной, а сессия ставила
  // «чисто» лишь бы закрыть. Найдено сценарием «объяснить поведение узла».
  //
  // Строка остаётся в протоколе: вопрос лозунга адресован исполнителю и
  // читается вместе с остальными. Печать она не держит.
  if (outcome === "лозунг") return "";
  if (!["чисто", "нет предмета", "нашлось"].includes(outcome))
    return "исход не из словаря";
  if (outcome === "нет предмета" && what === "")
    return "нет предмета без причины";
  // «Чисто» по архитектурному ядру обязано назвать основание.
  //
  // У находки форма спрашивает адрес, слова и судьбу, и сверка их проверяет.
  // У «чисто» не спрашивалось НИЧЕГО — пустая клетка закрывала строку. Под
  // давлением ста пятидесяти трёх строк такой вердикт сползает к самому
  // быстрому, и отличить обдуманное «чисто» от проставленного нельзя ничем.
  //
  // Спрашивается не у всех: деталь видна в строке, и её отсутствие тоже.
  // Ядро — про форму целого, и там вердикт без основания бессодержателен.
  if (outcome === "чисто" && what === "" && BAR_CORE.has(id))
    return "чисто без основания";
  if (outcome !== "нашлось") return "";
  if (what === "") return "находка без слов";
  if (!["починено", "предложено", "отложено"].includes(fate))
    return "судьба не из словаря";
  // Починка на задаче чтения — подмена задачи, и обратное тоже верно:
  // «предложено» на задаче изменения оставляет находку неисправленной там,
  // где правила требуют чинить.
  if (fate === "предложено" && kind !== "на чтение")
    return "предложено на задаче изменения";
  // Адрес — то единственное в находке, что вообще можно проверить. Находка
  // без проверяемого адреса неотличима от строки, написанной не глядя.
  return /^`?.+?:[0-9]+`?$/.test(addr) ? "" : "адрес не вида путь:строка";
};
/** Ряды комментариев в тексте: род, строка начала, длина в словах.
 *
 * Возвращает `род:строка:слов` через точку с запятой, пустую строку — рядов
 * нет. Род `line` — слитный ряд двух косых, род `block` — блок в звёздочках.
 *
 * **Мера — слово, а не строка.** Строка это формат: форматтер переносит
 * длинную строку в две, и порог по строкам начинает зависеть от ширины поля.
 * Слово от переноса не зависит.
 *
 * **Роды считаются порознь**, потому что назначение у них разное: ряд `//`
 * поясняет соседнюю строку, блок держит контракт узла. Один порог на оба
 * означал бы, что строгий запрещает контракт, а мягкий разрешает поэму.
 *
 * Комментарий опознаётся только ОТКРЫТЫЙ С НАЧАЛА СТРОКИ — тем же признаком,
 * что и в `codeOf`, и по той же причине: две косые сплошь и рядом стоят
 * внутри строкового литерала. Хвостовой комментарий в конце строки кода не
 * считается вовсе, и это не упущение: в одну строку поэма не помещается.
 *
 * Строки с тегом (`@param`, `@returns`) в счёт не идут: это структурный
 * контракт, а не проза, и длина его растёт с числом параметров.
 */
export const commentRunsOf = (text) => {
  const runs = [];
  let kind = null;
  let at = 0;
  let words = 0;
  let rows = 0;
  let inBlock = false;
  const close = () => {
    if (kind !== null) runs.push(kind + SEP2 + at + SEP2 + words + SEP2 + rows);
    kind = null;
    words = 0;
    rows = 0;
  };
  const lines = text.split(NEWLINE);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    let now = null;
    if (inBlock) {
      now = "block";
      if (line.includes("*/")) inBlock = false;
    } else if (line.startsWith("/*")) {
      now = "block";
      if (!line.includes("*/")) inBlock = true;
    } else if (line.startsWith("//")) now = "line";
    if (now === null) {
      close();
      continue;
    }
    if (kind !== null && kind !== now) close();
    if (kind === null) at = i + 1;
    kind = now;
    rows += 1;
    const bare = line
      .replace(/^(\/\*+|\*+\/|\*|\/\/)/, "")
      .replace(/\*\/$/, "")
      .trim();
    if (bare.startsWith("@")) continue;
    for (const w of bare.split(/\s+/)) if (w.length > 0) words += 1;
  }
  close();
  return runs.join(SEP1);
};
