/** Согласие строки протокола с моделью предмета — чистая часть.
 *
 * Вход — `критерий|исход|что|род|модель`, где модель — строки через `;`,
 * каждая `номер:вид:пометка` (`П3:ресурс:нет` — ресурс без снятия,
 * `П4:связь:нет` — связь, не записанная в базе, `П5:зависит:чужое` —
 * внутренность чужой единицы мимо её входа, `П6:наружу:` — имя уходит из
 * пакета). Номер строки модели пишется кириллической `П`: латинские
 * `M1`–`M6` уже заняты критериями политики. Выход — дыра словами или пустая строка.
 *
 * Правила универсальны: ни одно не знает ни фреймворка, ни проекта — только
 * виды строк модели, которые есть у любого кода: зависимость, ресурс, связь
 * мимо импорта, выход наружу. Замерено разбором узла, где по каждому из
 * этих видов было ровно то, что сессия закрыла словом «чисто». */
export const barModelFault = (row) => {
  const [id, outcome, what, kind, modelText, level, fate] = row.split("|");
  const model = modelRowsOf(modelText);
  const pick = (sort, mark) =>
    model.filter((m) => m.sort === sort && (mark === undefined || m.mark === mark));
  const fresh = (list) => list.filter((m) => m.delta !== "");
  const ids = (list) => list.map((m) => m.mid).join(", ");
  const cited = citedIds(what);
  // «Починено», а модель, собранная по нынешнему коду, показывает то же
  // самое: починка не случилась. Спрашивается о фактах, которые режут сами.
  if (outcome === "нашлось" && fate === "починено") {
    if (id === "A5" && pick("направление", "против правила").length > 0)
      return (
        "починено, а ребро против правила в модели осталось: " +
        ids(pick("направление", "против правила"))
      );
    if (id === "A9-бис" && fresh(pick("цикл")).length > 0)
      return "починено, а цикл в модели остался: " + ids(fresh(pick("цикл")));
    return "";
  }
  if (outcome !== "чисто" && outcome !== "нет предмета") return "";
  // Беспредметность, опровергнутая моделью: предмет в ней есть.
  if (outcome === "нет предмета") {
    const present = {
      F1: pick("ресурс"),
      F2: pick("ресурс"),
      E4: pick("ресурс"),
      C12: pick("ресурс"),
      A13: pick("связь"),
      B9: kind === "на изменение" ? pick("наружу") : [],
      C6: [...pick("состояние"), ...pick("источник")],
      "C6-бис": pick("писатель"),
      "A9-бис": pick("цикл"),
      A5: [...pick("направление", "против правила"), ...pick("граница")],
      A12: pick("устойчивость"),
    }[id];
    if (present !== undefined && present.length > 0)
      return "нет предмета, а в модели он есть: " + ids(present);
    return "";
  }
  // Факты, которые режут сами: «чисто» при них ложно без суждения.
  if ((id === "F2" || id === "E4") && pick("ресурс", "нет").length > 0)
    return "чисто, а снятия нет у ресурса " + ids(pick("ресурс", "нет"));
  if (id === "A5" && pick("направление", "против правила").length > 0)
    return (
      "чисто, а ребро идёт против правила направления: " +
      ids(pick("направление", "против правила"))
    );
  if (id === "A9-бис" && fresh(pick("цикл")).length > 0)
    return "чисто, а правка завела цикл: " + ids(fresh(pick("цикл")));
  // Остальное — не приговор, а вопрос: общая константа бывает словарём, вход
  // чужой единицы — законно обойдённым, второй писатель — объявленным
  // порядком, новое состояние — не копией чужого. Вердикт «чисто» обязан
  // назвать такие строки, то есть ответить на них, а не пройти мимо.
  const named = (list) => list.filter((m) => !cited.has(m.n));
  const asks = [
    ["A13", pick("связь", "нет"), "связь не записана в базе и в основании не названа"],
    ["A5", pick("граница"), "внутренность чужой единицы берётся мимо её входа и в основании не названа"],
    ["B7", pick("граница"), "внутренность чужой единицы берётся мимо её входа и в основании не названа"],
    ["A9-бис", pick("цикл"), "цикл через предмет в основании не назван"],
    ["C6-бис", pick("писатель"), "у источника больше одного писателя, и в основании он не назван"],
    ["A6", fresh(pick("состояние")), "правка завела состояние, и в основании не сказано, почему это не второй источник"],
    ["C7", fresh(pick("состояние")), "правка завела состояние, и в основании не сказано, почему оно не производное"],
    ["B7", fresh(pick("поверхность")), "поверхность узла сдвинулась, и в основании это не названо"],
    ["A12", pick("устойчивость"), "зависимость к менее устойчивому в основании не названа"],
  ];
  for (const [who, list, words] of asks)
    if (id === who && named(list).length > 0)
      return "чисто, а " + words + ": " + ids(named(list));
  // «Чисто» ядра стоит на факте СВОЕГО уровня: вердикт об источнике истины —
  // на строке об источниках приложения, о направлении — на строке о слое.
  // Прежде годилась строка любого уровня, а модель знала один узел.
  if (barCitesModel(id) && model.length > 0) {
    const same = model.filter((m) => m.level === level);
    const pool = same.length > 0 ? same : model;
    if (!pool.some((m) => cited.has(m.n)))
      return same.length > 0
        ? "чисто без опоры на модель своего уровня: назвать строку уровня «" +
            level +
            "»"
        : "чисто без опоры на модель: назвать её строку";
  }
  return "";
};

/** Итог по уровню — строка таблицы «Итог по уровням», чистая её часть.
 *
 * Вход — `уровень|что|держится|опора|модель|открытых находок уровня`. Выход —
 * дыра словами или пустая строка. Уровень держится, пока открытых находок на
 * нём нет, и наоборот: итог, спорящий с исходами, сводом не является. */
export const barLevelFault = (row) => {
  const [level, what, holds, basis, modelText, openText] = row.split("|");
  const said = (holds ?? "").trim();
  if ((what ?? "").trim() === "")
    return "не сказано, что на уровне изменилось или как он устроен";
  if (said === "") return "не сказано, держится ли уровень";
  if (said !== "да" && said !== "нет")
    return "держится не из словаря: «" + said + "»";
  const same = modelRowsOf(modelText).filter((m) => m.level === level);
  const cited = citedIds((what ?? "") + " " + (basis ?? ""));
  if (same.length > 0 && !same.some((m) => cited.has(m.n)))
    return "опора не называет ни одной строки модели этого уровня";
  const open = Number(openText ?? "0");
  if (said === "да" && open > 0)
    return "держится, а открытых находок уровня: " + open;
  if (said === "нет" && open === 0)
    return "не держится, а открытой находки уровня нет";
  return "";
};

/** Сдвиги модели без ответа.
 *
 * Вход — `модель|всё, что протокол ответил`: итог по уровням, основания и
 * находки. Выход — номера строк со сдвигом, которых ответ не называет, либо
 * пустая строка. Сдвиг, о котором промолчали, — ровно та поломка, которой
 * строки правки не показывают. */
export const barDeltaFault = (row) => {
  const cut = row.indexOf("|");
  const model = modelRowsOf(cut < 0 ? row : row.slice(0, cut));
  const cited = citedIds(cut < 0 ? "" : row.slice(cut + 1));
  const loose = model.filter((m) => m.delta !== "" && !cited.has(m.n));
  return loose.length === 0
    ? ""
    : "сдвиг без ответа: " + loose.map((m) => m.mid).join(", ");
};

/** Называет ли текст адрес ЦЕЛИКОМ, а не как начало другого адреса.
 *
 * Вход — `адрес|текст`. Папка засчитывается с косой на конце и без неё.
 * Прежде запись решения узнавалась вхождением подстроки, и адрес `src/`
 * находился в любом тексте, где назван хоть один путь под ним: тест,
 * объявленный вне своей папки, проходил без всякого решения о нём.
 */
export const namesAddress = (row) => {
  const cut = row.indexOf("|");
  const addr = row.slice(0, cut).replace(/\/$/, "");
  const esc = addr.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(
    "(^|[\\s`(«\"'])" + esc + "/?(?=$|[\\s`)»\"',.;:])",
    "m",
  ).test(row.slice(cut + 1));
};

/** Первая графа строки таблицы; не строка таблицы — пусто.
 *
 * Черта делит так же, как её считает разметка: экранированная не делит.
 * Описанием файла карта считает ЕГО строку, где путь стоит первой графой,
 * а не упоминание в чужой: упомянутый файл считался описанным, и долг
 * описания убывал без описания.
 */
export const firstCellOf = (line) => {
  const bare = line.trim();
  if (!bare.startsWith("|")) return "";
  for (let i = 1; i < bare.length; i += 1) {
    if (bare[i] === "\\") {
      i += 1;
      continue;
    }
    if (bare[i] === "|") return bare.slice(1, i).trim();
  }
  return bare.slice(1).trim();
};

/** Входит ли критерий в архитектурное ядро. Наружу — для свода: он печатает
 * такие строки помеченными, чтобы клетка основания не выглядела лишней. */
export const barCoreCriterion = (id) => BAR_CORE.has(id);
export const barRowFault = (row) => {
  // Шестая клетка — идентификатор критерия. Прежде строка несла пять: ядро
  // планки спрашивают поимённо, и без имени спросить его нечем.
  const [kind, outcome, addr, what, fate, id] = row
    .split("|")
    .map((c) => c.trim());
  if (outcome === "") return "исход не поставлен";
  // «Лозунг» — не исход, а признак того, что исхода тут быть не может.
  //
  // Политика объявляет часть пунктов лозунгами прямо: «у него нет величины
  // отсчёта и способа измерения, поэтому по нему нельзя ни оценить дифф, ни
  // сослаться на него как на нарушение». Протокол при этом требовал исход по
  // каждому и числил такие строки дырами — то есть машина требовала ровно
  // той оценки, которую доктрина объявила невозможной, а сессия ставила
  // «чисто» лишь бы закрыть. Найдено сценарием «объяснить поведение узла».
  //
  // Строка остаётся в протоколе: вопрос лозунга адресован исполнителю и
  // читается вместе с остальными. Печать она не держит.
  if (outcome === "лозунг") return "";
  if (!["чисто", "нет предмета", "нашлось"].includes(outcome))
    return "исход не из словаря";
  if (outcome === "нет предмета" && what === "")
    return "нет предмета без причины";
  // «Чисто» по архитектурному ядру обязано назвать основание.
  //
  // У находки форма спрашивает адрес, слова и судьбу, и сверка их проверяет.
  // У «чисто» не спрашивалось НИЧЕГО — пустая клетка закрывала строку. Под
  // давлением ста пятидесяти трёх строк такой вердикт сползает к самому
  // быстрому, и отличить обдуманное «чисто» от проставленного нельзя ничем.
  //
  // Спрашивается не у всех: деталь видна в строке, и её отсутствие тоже.
  // Ядро — про форму целого, и там вердикт без основания бессодержателен.
  if (outcome === "чисто" && what === "" && BAR_CORE.has(id))
    return "чисто без основания";
  if (outcome !== "нашлось") return "";
  if (what === "") return "находка без слов";
  // «Вопрос» — развилка, которую решает разработчик: находка записана
  // вопросом в список вопросов, и до ответа ни чинить, ни откладывать её
  // нельзя. Прежде судеб для неё не было: «отложено» доктрина разрешает только
  // ПОСЛЕ ответа, «починено» — подмена решения, и печать ставилась ценой
  // неверной судьбы. Замерено на задаче изменения, где находкой была смена
  // ответа публичного узла на краевом входе.
  if (!["починено", "предложено", "отложено", "вопрос"].includes(fate))
    return "судьба не из словаря";
  // Починка на задаче чтения — подмена задачи, и обратное тоже верно:
  // «предложено» на задаче изменения оставляет находку неисправленной там,
  // где правила требуют чинить.
  if (fate === "предложено" && kind !== "на чтение")
    return "предложено на задаче изменения";
  // Адрес — то единственное в находке, что вообще можно проверить. Находка
  // без проверяемого адреса неотличима от строки, написанной не глядя.
  return /^`?.+?:[0-9]+`?$/.test(addr) ? "" : "адрес не вида путь:строка";
};
/** Ряды комментариев в тексте: род, строка начала, длина в словах.
 *
 * Возвращает `род:строка:слов` через точку с запятой, пустую строку — рядов
 * нет. Род `line` — слитный ряд двух косых, род `block` — блок в звёздочках.
 *
 * **Мера — слово, а не строка.** Строка это формат: форматтер переносит
 * длинную строку в две, и порог по строкам начинает зависеть от ширины поля.
 * Слово от переноса не зависит.
 *
 * **Роды считаются порознь**, потому что назначение у них разное: ряд `//`
 * поясняет соседнюю строку, блок держит контракт узла. Один порог на оба
 * означал бы, что строгий запрещает контракт, а мягкий разрешает поэму.
 *
 * Комментарий опознаётся только ОТКРЫТЫЙ С НАЧАЛА СТРОКИ — тем же признаком,
 * что и в `codeOf`, и по той же причине: две косые сплошь и рядом стоят
 * внутри строкового литерала. Хвостовой комментарий в конце строки кода не
 * считается вовсе, и это не упущение: в одну строку поэма не помещается.
 *
 * Строки с тегом (`@param`, `@returns`) в счёт не идут: это структурный
 * контракт, а не проза, и длина его растёт с числом параметров.
 */
export const commentRunsOf = (text) => {
  const runs = [];
  let kind = null;
  let at = 0;
  let words = 0;
  let rows = 0;
  let inBlock = false;
  const close = () => {
    if (kind !== null) runs.push(kind + SEP2 + at + SEP2 + words + SEP2 + rows);
    kind = null;
    words = 0;
    rows = 0;
  };
  const lines = text.split(NEWLINE);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    let now = null;
    if (inBlock) {
      now = "block";
      if (line.includes("*/")) inBlock = false;
    } else if (line.startsWith("/*")) {
      now = "block";
      if (!line.includes("*/")) inBlock = true;
    } else if (line.startsWith("//")) now = "line";
    if (now === null) {
      close();
      continue;
    }
    if (kind !== null && kind !== now) close();
    if (kind === null) at = i + 1;
    kind = now;
    rows += 1;
    const bare = line
      .replace(/^(\/\*+|\*+\/|\*|\/\/)/, "")
      .replace(/\*\/$/, "")
      .trim();
    if (bare.startsWith("@")) continue;
    for (const w of bare.split(/\s+/)) if (w.length > 0) words += 1;
  }
  close();
  return runs.join(SEP1);
};
